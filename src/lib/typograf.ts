/**
 * Типографика для русского текста: висячие предлоги и союзы склеиваются
 * со следующим словом неразрывным пробелом, тире и числа не отрываются.
 * Применяется ко всем текстовым узлам страницы при сборке (см. Base.astro).
 */
const SHORT = [
  'а','в','во','и','к','ко','о','об','обо','от','ото','с','со','у','за','из','изо','на','не','ни','но','по','под','при','про','до','да','же','ли','бы','б','ль','то','из-за','из-под','над','без','для','или','что','как','так','уж','ну','ещё','еще',
];
const shortRe = new RegExp(`(^|[\\s(«"„])(${SHORT.join('|')}) `, 'gi');

export function typograf(text: string): string {
  return (
    text
      // предлог/союз + пробел → неразрывный пробел (дважды: «и в», «не на»)
      .replace(shortRe, '$1$2 ')
      .replace(shortRe, '$1$2 ')
      // число + единица/знак: 40 %, 300 млн, 5 642 м
      .replace(/(\d) (%|п\.п\.|млн|млрд|тыс\.|м\b|с\b|мин\b|ч\b|₽|руб\.|чел\.)/g, '$1 $2')
      // пробел перед тире → неразрывный
      .replace(/ —/g, ' —')
      // короткие местоимения-частицы: «я хочу», «вы довольны» — не трогаем, они не висячие по правилам
  );
}
